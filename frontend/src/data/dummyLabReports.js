export function pickLocalizedPair(pair, lang) {
  if (!pair || typeof pair !== 'object') return '';
  return lang === 'hi' ? pair.hi || pair.en || '' : pair.en || pair.hi || '';
}

export function getReportsForFarmer(reports, farmerKey) {
  return reports.filter((r) => r.farmerKey === farmerKey).sort((a, b) => (a.date < b.date ? 1 : -1));
}
